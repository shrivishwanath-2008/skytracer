def main() -> None:
    seen: set[str] = set()
    rows = []
    for name, ra, dec, mag in STARS:
        key = name.lower()
        if key in seen:
            continue
        seen.add(key)
        rows.append({
            "name": name,
            "ra_hours": round(ra, 6),
            "dec_deg": round(dec, 6),
            "magnitude": round(mag, 2),
        })
    rows.sort(key=lambda r: r["magnitude"])
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(rows, indent=2), encoding="utf-8")
    print(f"Wrote {len(rows)} stars to {OUT}")


if __name__ == "__main__":
    main()
